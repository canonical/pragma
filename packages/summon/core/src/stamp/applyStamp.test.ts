describe("runTaskWithStamp", () => {
  it("runs a pure task without stamp option", async () => {
    const result = await runTaskWithStamp(pure(42));
    expect(result).toBe(42);
  });

  it("runs a pure task with stamp option (no WriteFile effects to stamp)", async () => {
    const result = await runTaskWithStamp(pure("done"), {
      stamp,
    });
    expect(result).toBe("done");
  });

  it("stamps WriteFile effect content when stamp is provided", async () => {
    const captured: Effect[] = [];
    const task = writeFile("/tmp/test-stamp-output.ts", "const x = 1;");

    await runTaskWithStamp(task, {
      stamp,
      onEffectStart: (effect) => {
        captured.push({ ...effect });
      },
    });

    const writeEffect = captured.find((e) => e._tag === "WriteFile");
    expect(writeEffect).toBeDefined();
    // The content should have been mutated before our onEffectStart was called
    expect((writeEffect as { content: string }).content).toContain(
      "Generated by test-gen v1.0.0",
    );
  });

  it("calls user-provided onEffectStart after stamping", async () => {
    const userCallback = vi.fn();
    const task = writeFile("/tmp/test-stamp-cb.ts", "hello");

    await runTaskWithStamp(task, {
      stamp,
      onEffectStart: userCallback,
    });

    expect(userCallback).toHaveBeenCalled();
    const callArg = userCallback.mock.calls[0][0];
    expect(callArg._tag).toBe("WriteFile");
  });

  it("does not modify non-WriteFile effects", async () => {
    const captured: Effect[] = [];
    // mkdir produces a MakeDir effect, not WriteFile
    const mkdirTask = task(mkdir("/tmp/test-stamp-dir"))
      .chain(() => task(writeFile("/tmp/test-stamp-dir/out.ts", "code")))
      .unwrap();

    await runTaskWithStamp(mkdirTask, {
      stamp,
      onEffectStart: (effect) => {
        captured.push({ ...effect });
      },
    });

    const mkdirEffect = captured.find((e) => e._tag === "MakeDir");
    expect(mkdirEffect).toBeDefined();
    // MakeDir effect should pass through unchanged
    expect(mkdirEffect?._tag).toBe("MakeDir");
  });
});
