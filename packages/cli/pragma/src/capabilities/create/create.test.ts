describe("declared generator bindings (PROTECTED)", () => {
  // CREATE_GENERATORS binds each noun's PER-NOUN facts (its generator-map key,
  // its framework axis, whether it reads the embedded manifest). The package
  // NAMES come from `pragma.conf.ts`; that correspondence is the subject of the
  // suite below. What is checkable against something outside either — the live
  // generator maps and the embedded manifest — is checked here.

  it("every binding resolves to the generator it names", async () => {
    const { pickGenerator } = await import("./pickGenerator.js");
    // `meta.name` is the generator's OWN identity, so a swapped `key` or a
    // framework the map does not carry turns this red — which `toBeDefined()`
    // on a non-nullable return could not.
    for (const framework of CREATE_GENERATORS.component.frameworks) {
      expect(pickGenerator("component", { framework }).meta.name).toBe(
        `component/${framework}`,
      );
    }
    expect(pickGenerator("package", {}).meta.name).toBe("package");
    expect(pickGenerator("application", {}).meta.name).toBe(
      "application/react",
    );
  });

  it("exactly the two source-run-only verbs publish the availability caveat", () => {
    // A LITERAL list, for the same reason `compiledCreate.subprocess.test.ts`
    // uses one: the caveat is DERIVED from `readsEmbeddedTemplates`, so an
    // assertion derived from the same bit would agree with itself no matter
    // which way the bit was flipped. These two are the nouns that test proves
    // refuse on a real compiled binary, so this is what the reference is held
    // to — and flipping the bit turns this red, along with the reference
    // drift-guard, in the same run.
    const caveated = createModule.verbs
      .filter((verb) => verb.summary.includes("Source-run only."))
      .map((verb) => verb.path.at(1));
    expect(caveated).toEqual(["package", "application"]);
    for (const verb of createModule.verbs) {
      const kind = verb.path.at(1);
      const gated = caveated.includes(kind);
      // The `doc` is what `tools.md` and the MCP tool description render, so
      // the explanation has to travel with the marker, and it quotes the
      // command it is about — a copy-paste between bindings is then visible.
      expect(verb.doc?.includes("UNSUPPORTED") ?? false, kind).toBe(gated);
      if (gated) {
        expect(verb.doc).toContain(`create ${kind}`);
        // And it still says what the verb MAKES. `doc ?? summary` means a doc
        // REPLACES the summary on the MCP surface, so a caveat alone left an
        // agent no statement anywhere of what `create_package` scaffolds.
        expect(verb.doc).toContain(
          verb.summary.replace(" Source-run only.", ""),
        );
      }
    }
  });

  it("the --framework enum offers the declared frameworks and defaults to one of them", () => {
    const framework = createVerbs.component.params.find(
      (p) => p.name === "framework",
    );
    // A `values: []` enum with a `default` would leave every `--framework`
    // rejected while `--help` still advertises a default — the hazard this names.
    // (That every value resolves is the test above.)
    expect(framework?.kind).toBe("enum");
    const values = (framework as { values: readonly string[] }).values;
    expect(values.length).toBeGreaterThan(0);
    expect(values).toContain(framework?.default);
  });

  it("embeds only the templates the component loader can key", async () => {
    const { TEMPLATES } = await import("./templates.embedded.generated.js");
    const keys = Object.keys(TEMPLATES);
    // summon-component's `qualifiedKey()` prefixes EVERY lookup with
    // `component/`, so any other entry ships dead weight the binary can never
    // read — and a binding embedded without a manifest-reading generator would
    // put one here. Non-empty first: `.every()` over an empty list is vacuous.
    expect(keys.length).toBeGreaterThan(0);
    expect(keys.filter((k) => !k.startsWith("component/"))).toEqual([]);
  });

  it("create surfaces exactly the three declared nouns", () => {
    // A LITERAL surface pin, deliberately not derived from CREATE_GENERATORS:
    // surfacing a noun also needs a hand-written prompt mirror, path param and
    // examples in create.verb.ts, so the surface is a deliberate SUBSET of what
    // the declared packages ship (`@canonical/summon-application` also ships
    // `domain`, `route` and `wrapper`). Pinning OUR three nouns rather than any
    // third-party package's generator list keeps an upstream release from
    // turning this red.
    expect(createModule.verbs.map((v) => v.path[1])).toEqual([
      "component",
      "package",
      "application",
    ]);
    // The same three, in the same order, in the binding table. The table's
    // `BOUND_NOUNS` is what its shortfall message counts and what decides which
    // declaration slot each noun reads, so a key added or dropped without moving
    // that tuple would leave the message reporting the wrong requirement. Also
    // literal, for the reason above.
    expect(Object.keys(CREATE_GENERATORS)).toEqual([
      "component",
      "package",
      "application",
    ]);
  });
});

describe("the generator declaration is load-bearing (PROTECTED)", () => {
  /**
   * The three inputs the build compares, read exactly as `scripts/build.ts`
   * reads them. `pickGenerator.ts` is read as TEXT, never imported: importing it
   * pulls summon-core, and the point is the literal specifiers in its source.
   */
  const live = (): DeclaredGeneratorCheck => ({
    declared: conf.generators,
    bound: Object.fromEntries(
      Object.entries(CREATE_GENERATORS).map(([noun, binding]) => [
        noun,
        binding.name,
      ]),
    ),
    statics: readStaticGeneratorImports(
      readFileSync(
        fileURLToPath(new URL("./pickGenerator.ts", import.meta.url)),
        "utf-8",
      ),
    ),
    dependencies: pkg.dependencies,
    embeddedNouns: Object.entries(CREATE_GENERATORS).flatMap(
      ([noun, binding]) => (binding.readsEmbeddedTemplates ? [noun] : []),
    ),
    embeddedFrom: readEmbeddedManifestImport(
      readFileSync(
        fileURLToPath(new URL("./create.verb.ts", import.meta.url)),
        "utf-8",
      ),
    ),
  });

  it("parses each declared source form and keeps a scoped name whole", () => {
    expect(
      parseGeneratorSource("npm:@canonical/summon-component@^0.33.0"),
    ).toEqual({
      kind: "npm",
      name: "@canonical/summon-component",
      range: "^0.33.0",
    });
    // The non-npm forms collapse to ONE arm — nothing reads a url or a path,
    // and nothing branches on git-versus-file either, so the type says neither.
    // What they promise is that the form is recognised.
    expect(
      parseGeneratorSource("git+https://example.invalid/g.git#main"),
    ).toEqual({ kind: "other" });
    expect(parseGeneratorSource("file:../local")).toEqual({ kind: "other" });
    expect(() => parseGeneratorSource("@canonical/x@1")).toThrow(/npm:<spec>/);
    expect(() => parseGeneratorSource("npm:plain")).toThrow(/version range/);
  });

  it("reads the static specifiers out of pickGenerator's own source", () => {
    // The residue the ruling cannot remove: `bun build --compile` bundles only
    // statically analysable specifiers, so these three literals must exist —
    // three of the four, the fourth being `create.verb.ts`'s embedded-manifest
    // import, pinned in its own case below. Read by NOUN (the `GENERATOR_MAPS`
    // entry), not by import order — biome sorts the import block
    // alphabetically, which is not declaration order.
    expect(live().statics).toEqual({
      component: "@canonical/summon-component",
      package: "@canonical/summon-package",
      application: "@canonical/summon-application",
    });
  });

  it("names the formatting when it recognises the file but reads no entry", () => {
    // The reader parses SOURCE TEXT, and the entry pattern pins the literal
    // `as unknown as GeneratorMap` cast — which `pickGenerator.ts`'s own
    // docblock says exists only until summon's `generate` variance is fixed
    // upstream. Before this, that one cosmetic deletion made the reader return
    // `{}` and `assertDeclaredGenerators` report, per noun, "has no static
    // generator import in pickGenerator.ts": false (the imports are on lines
    // 1-4) and it sent a builder to add what was already there.
    //
    // The fixture is the real file with exactly that phrase removed, so this
    // fails if the pattern and `pickGenerator.ts` ever stop agreeing.
    const real = readFileSync(
      fileURLToPath(new URL("./pickGenerator.ts", import.meta.url)),
      "utf-8",
    );
    const decast = real.replaceAll(" as unknown as GeneratorMap", "");
    expect(decast).not.toBe(real);
    expect(() => readStaticGeneratorImports(decast)).toThrow(
      /could not read GENERATOR_MAPS out of pickGenerator\.ts/,
    );
    // And an unrelated string is still not this file: no false alarm.
    expect(readStaticGeneratorImports("const x = 1;\n")).toEqual({});
  });

  it("reads the embedded-manifest package out of create.verb's own source", () => {
    // The FOURTH literal specifier, and the one the guard could not see:
    // `scripts/build.ts` harvests `.ejs` for whichever binding declares
    // `readsEmbeddedTemplates`, while this import decides whose loader registry
    // receives them. A LITERAL, like the `statics` case above and for the same
    // reason — the alternative recomputes the value from the binding it is
    // supposed to hold.
    expect(live().embeddedFrom).toBe("@canonical/summon-component");
    expect(live().embeddedNouns).toEqual(["component"]);
  });

  it("fails when the embedded manifest is injected into another package", () => {
    // The measured fork failure this closes: declare a different component
    // generator, edit `pickGenerator.ts` (the only other file the reference
    // page used to name) and stop. The build PASSED, `TEMPLATE_ROOTS` harvested
    // the fork's templates, and `create.verb.ts` still called
    // `setEmbeddedTemplates` on `@canonical/summon-component` — so `create
    // component` from the binary died on the template read, misreported by
    // `isModuleNotFound`'s backstop as "run it from a source checkout".
    expect(() =>
      assertDeclaredGenerators({
        ...live(),
        embeddedFrom: "@acme/summon-other",
      }),
    ).toThrow(/injects the embedded manifest into @acme\/summon-other/);
    expect(() =>
      assertDeclaredGenerators({ ...live(), embeddedFrom: undefined }),
    ).toThrow(/imports no "<package>\/embedded" module/);
  });

  it("the shipped declaration, bindings and dependencies agree", () => {
    expect(() => assertDeclaredGenerators(live())).not.toThrow();
  });

  it("binds each noun to the package the distribution declares, in order", () => {
    // A LITERAL noun → package map, the same technique as the `statics` case
    // above. This used to assert `Object.values(bound)` against
    // `conf.generators.map(g => g.name)` — but every `name:` in
    // `CREATE_GENERATORS` IS `conf.generators[i].name`, so both sides reduced to
    // the same three reads and the assertion compared the declaration with
    // itself. The comment defending that said a literal "would just be the
    // hand-copy again"; it is the opposite — the hand-copy was in `src/`, where
    // nothing checked it, and this is a pin that must be edited deliberately
    // when the declaration moves.
    //
    // Non-vacuous, and MEASURED against the mutation that discriminates the two
    // forms: swap the first two entries of `pragma.conf.ts#generators` and the
    // old assertion still holds (both sides move together) while this one fails.
    // A positional zip over a reordered declaration re-binds two nouns, which is
    // the failure the old form was written to catch and could not.
    expect(live().bound).toEqual({
      component: "@canonical/summon-component",
      package: "@canonical/summon-package",
      application: "@canonical/summon-application",
    });
  });

  it("fails when a binding names a package the declaration does not", () => {
    expect(() =>
      assertDeclaredGenerators({
        ...live(),
        bound: { ...live().bound, package: "@acme/other" },
      }),
    ).toThrow(/create package binds @acme\/other/);
  });

  it("fails when the declaration is reordered under the positional zip", () => {
    // The binding table zips `generators` POSITIONALLY, so swapping two entries
    // silently re-binds two nouns. This is what makes that impossible: the
    // static specifier for each noun is the same string as its bound name, and
    // a swap breaks two of the three.
    const base = live();
    const [a, b, c] = base.declared;
    expect(() =>
      assertDeclaredGenerators({
        ...base,
        declared: [b, a, c] as typeof base.declared,
        bound: { component: b.name, package: a.name, application: c.name },
      }),
    ).toThrow(/pickGenerator\.ts statically imports/);
  });

  it("fails when a declared source names a different package than its entry", () => {
    expect(() =>
      assertDeclaredGenerators({
        ...live(),
        declared: [
          {
            name: "@canonical/summon-component",
            source: "npm:@canonical/summon-package@^0.33.0",
          },
          ...live().declared.slice(1),
        ],
      }),
    ).toThrow(/which names @canonical\/summon-package/);
  });

  it("fails when a declared range disagrees with the dependency that links", () => {
    // The claim that makes `source` load-bearing rather than decorative: the
    // DEPENDENCY decides which generator code is compiled into the binary, so a
    // monorepo version bump that leaves the declaration at the old range now
    // fails the build instead of publishing a range nothing installed.
    expect(() =>
      assertDeclaredGenerators({
        ...live(),
        dependencies: {
          ...pkg.dependencies,
          "@canonical/summon-component": "^9.0.0",
        },
      }),
    ).toThrow(/package\.json depends on \^9\.0\.0/);
  });

  it("fails when a declared generator is not a dependency at all", () => {
    const { "@canonical/summon-application": _dropped, ...rest } =
      pkg.dependencies;
    expect(() =>
      assertDeclaredGenerators({ ...live(), dependencies: rest }),
    ).toThrow(/not in this package's dependencies/);
  });
});
